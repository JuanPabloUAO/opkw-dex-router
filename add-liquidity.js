const fs=require('fs'); const {ethers}=require('ethers'); require('dotenv').config();
(async()=>{
 const d=JSON.parse(fs.readFileSync('deployed.json','utf8'));
 const t=JSON.parse(fs.readFileSync('testtoken.json','utf8'));
 const c=JSON.parse(fs.readFileSync('compiled.json','utf8'));
 const p=new ethers.providers.JsonRpcProvider('http://127.0.0.1:9545');
 const w=new ethers.Wallet(process.env.PRIVATE_KEY,p);
 const W=new ethers.Contract(d.wopkw,c['WOPKW.sol']['WOPKW'].abi,w);
 const T=new ethers.Contract(t.testToken,c['TestToken.sol']['TestToken'].abi,w);
 const R=new ethers.Contract(d.router,c['OPKWRouter.sol']['OPKWRouter'].abi,w);
 const F=new ethers.Contract(d.factory,c['OPKWFactory.sol']['OPKWFactory'].abi,w);
 const amtW=ethers.utils.parseEther('0.1'); const amtT=ethers.utils.parseEther('100');
 console.log('1. Wrapping 0.1 OPKW -> WOPKW...');
 let tx=await W.deposit({value:amtW}); await tx.wait();
 console.log('WOPKW bal =',ethers.utils.formatEther(await W.balanceOf(w.address)));
 console.log('2. Approving Router...');
 tx=await W.approve(d.router,amtW); await tx.wait();
 tx=await T.approve(d.router,amtT); await tx.wait();
 console.log('3. Adding Liquidity 0.1 WOPKW + 100 WOLFTEST...');
 const dl=Math.floor(Date.now()/1000)+3600;
 tx=await R.addLiquidity(d.wopkw,t.testToken,amtW,amtT,0,0,w.address,dl,{gasLimit:500000}); const rc=await tx.wait();
 console.log('addLiquidity tx =',rc.transactionHash);
 const pair=await F.getPair(d.wopkw,t.testToken);
 console.log('PAIR =>',pair);
 const P=new ethers.Contract(pair,c['OPKWPair.sol']['OPKWPair'].abi,p);
 const r=await P.getReserves();
 console.log('reserve0 =',ethers.utils.formatEther(r._reserve0),'reserve1 =',ethers.utils.formatEther(r._reserve1));
 console.log('LP bal =',ethers.utils.formatEther(await P.balanceOf(w.address)));
 fs.writeFileSync('pair.json',JSON.stringify({pair,wolftest:t.testToken,wopkw:d.wopkw},null,2));
 console.log('SAVED pair.json - LIQUIDITY-OK');
})();
